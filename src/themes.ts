export type ThemeId =
  | 'main'
  | 'preview-one'
  | 'coral'
  | 'forest'
  | 'ocean'
  | 'slate'
  | 'sunset'
  | 'mono'
  | 'sand'
  | 'berry'
  | 'midnight'
  | 'aurora';

export interface Theme {
  id: ThemeId;
  name: string;
  dark: boolean;
  /** short tagline shown in the switcher */
  tagline: string;
  /** CSS variable values applied to :root */
  vars: Record<string, string>;
}

const baseVars = {
  '--radius-sm': '0.5rem',
  '--radius': '0.625rem',
  '--radius-lg': '0.75rem',
  '--radius-xl': '0.875rem',
  '--shadow-xs': '0 1px 2px rgba(16,24,40,0.05)',
  '--shadow-card': '0 1px 2px rgba(16,24,40,0.04), 0 2px 6px -2px rgba(16,24,40,0.06)',
  '--shadow-hover': '0 2px 4px -2px rgba(16,24,40,0.06), 0 12px 28px -8px rgba(16,24,40,0.14)',
  '--shadow-pop': '0 4px 8px -4px rgba(16,24,40,0.08), 0 24px 56px -16px rgba(16,24,40,0.24)',
  '--font-sans': "'DM Sans', system-ui, -apple-system, sans-serif",
  '--font-display': "'Manrope', system-ui, sans-serif",
};

function makeTheme(
  id: ThemeId,
  name: string,
  tagline: string,
  dark: boolean,
  colors: Record<string, string>,
  fonts?: Partial<Record<'--font-sans' | '--font-display', string>>,
): Theme {
  return {
    id,
    name,
    tagline,
    dark,
    vars: { ...baseVars, ...colors, ...(fonts ?? {}) },
  };
}

