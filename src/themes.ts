export type ThemeId =
  | 'coral'
  | 'forest'
  | 'ocean'
  | 'slate'
  | 'sunset'
  | 'ybuy'
  | 'sand'
  | 'berry'
  | 'midnight'
  | 'aurora';

export interface Theme {
  id: ThemeId;
  name: string;
  dark: boolean;
  /** short tagline shown in the switcher */
  tagline: string;
  /** CSS variable values applied to :root */
  vars: Record<string, string>;
}

const baseVars = {
  '--radius-sm': '0.25rem',
  '--radius': '0.375rem',
  '--radius-lg': '0.5rem',
  '--radius-xl': '0.75rem',
  '--shadow-xs': 'none',
  '--shadow-card': 'none',
  '--shadow-hover': '0 2px 6px rgba(17,17,17,0.08)',
  '--shadow-pop': '0 8px 24px rgba(0,0,0,0.16)',
  '--font-sans': "'DM Sans', system-ui, -apple-system, sans-serif",
  '--font-display': "'Manrope', 'DM Sans', system-ui, sans-serif",
};

function makeTheme(
  id: ThemeId,
  name: string,
  tagline: string,
  dark: boolean,
  colors: Record<string, string>,
  fonts?: Partial<Record<'--font-sans' | '--font-display', string>>,
): Theme {
  return {
    id,
    name,
    tagline,
    dark,
    vars: { ...baseVars, ...colors, ...(fonts ?? {}) },
  };
}

