begin;
lock table public.profiles in share row exclusive mode;

create sequence public.customer_id_sequence as bigint minvalue 1 maxvalue 9999999999 no cycle;
revoke all on sequence public.customer_id_sequence from public, anon, authenticated, service_role;

-- Retain only the issued identifier, never the deleted customer's personal data.
create table public.customer_id_registry (
  customer_id text primary key check (customer_id ~ '^YB-[0-9]{10}$'),
  issued_at timestamptz not null default now()
);
alter table public.customer_id_registry enable row level security;
revoke all on public.customer_id_registry from public, anon, authenticated, service_role;

create function public.protect_customer_id_registry()
returns trigger language plpgsql set search_path = '' as $$
begin
  raise exception 'Issued Customer IDs cannot be changed or reused' using errcode = '42501';
end;
$$;
revoke all on function public.protect_customer_id_registry() from public, anon, authenticated, service_role;
create trigger customer_id_registry_immutable
  before update or delete or truncate on public.customer_id_registry
  for each statement execute function public.protect_customer_id_registry();

alter table public.profiles add column customer_id text unique
  references public.customer_id_registry(customer_id);

create function public.assign_customer_id()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    if new.id is distinct from old.id or
      (old.customer_id is not null and new.customer_id is distinct from old.customer_id) then
      raise exception 'Customer identity is immutable' using errcode = '42501';
    end if;
    if old.customer_id is not null then return new; end if;
  end if;
  if new.customer_id is not null then
    raise exception 'Customer IDs are generated by the server' using errcode = '42501';
  end if;
  new.customer_id := 'YB-' || lpad(nextval('public.customer_id_sequence')::text, 10, '0');
  insert into public.customer_id_registry(customer_id) values (new.customer_id);
  return new;
end;
$$;
revoke all on function public.assign_customer_id() from public, anon, authenticated, service_role;
create trigger profiles_customer_identity
  before insert or update on public.profiles
  for each row execute function public.assign_customer_id();

update public.profiles set customer_id = null where customer_id is null;

-- Repair a missing profile without changing existing profile data or Auth UUIDs.
insert into public.profiles(id, full_name, email, avatar_url, created_at)
select u.id,
  coalesce(u.raw_user_meta_data->>'full_name', u.raw_user_meta_data->>'name', u.email, 'YBuy member'),
  coalesce(u.email, ''), u.raw_user_meta_data->>'avatar_url', u.created_at
from auth.users u where not exists (select 1 from public.profiles p where p.id = u.id)
on conflict (id) do nothing;

alter table public.profiles alter column customer_id set not null;
revoke select (customer_id) on public.profiles from public, anon, authenticated;

create or replace function public.admin_list_users(p_search text default null, p_limit int default 25, p_offset int default 0)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_limit int := least(greatest(coalesce(p_limit, 25), 1), 100);
  v_offset int := greatest(coalesce(p_offset, 0), 0);
  v jsonb;
begin
  perform public.admin_require('users.manage');
  if length(coalesce(p_search, '')) > 254 then
    raise exception 'Search must contain at most 254 characters' using errcode = '22023';
  end if;
  with base as (
    select p.id, p.customer_id, p.full_name, p.email, p.phone, p.created_at,
      r.reason as restricted_reason, r.restricted_at,
      (select count(*) from public.listings l where l.owner_id = p.id) as listing_count,
      (a.user_id is not null and a.active) as is_admin
    from public.profiles p
    left join public.user_restrictions r on r.user_id = p.id
    left join public.admin_users a on a.user_id = p.id
    where p_search is null or p_search = ''
      or strpos(lower(p.full_name), lower(p_search)) > 0
      or strpos(lower(p.email), lower(p_search)) > 0
      or strpos(p.customer_id, upper(btrim(p_search))) > 0
  ), page as (select * from base order by created_at desc, id limit v_limit offset v_offset)
  select jsonb_build_object('total', (select count(*) from base),
    'rows', coalesce((select jsonb_agg(to_jsonb(page) order by page.created_at desc, page.id) from page), '[]'::jsonb)) into v;
  return v;
end;
$$;
commit;
