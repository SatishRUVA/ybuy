create or replace function public.expire_listing_checkouts(p_listing_id uuid)
returns integer language plpgsql security definer set search_path = '' as $$
declare
  v_booking public.bookings;
  v_policy public.booking_cancellation_policies;
  v_count integer:=0;
  v_cancellation_id uuid;
begin
  perform 1 from public.listings where id=p_listing_id for update;
  for v_booking in
    update public.bookings set status='cancelled',checkout_expired_at=clock_timestamp()
      where listing_id=p_listing_id and status='pending_payment' and checkout_expires_at<=clock_timestamp()
        and not exists(select 1 from public.payments p where p.booking_id=bookings.id and p.status='succeeded')
      returning *
  loop
    select * into v_policy from public.booking_cancellation_policies
      where effective_from<=v_booking.checkout_expired_at
        and (effective_to is null or effective_to>v_booking.checkout_expired_at)
      order by effective_from desc,version desc limit 1;
    insert into public.booking_cancellations(
      booking_id,initiator_role,cancellation_type,reason,previous_booking_status,policy_id,policy_version
    ) values(v_booking.id,'system','checkout_expired','Checkout reservation expired.','pending_payment',
      v_policy.id,v_policy.version)
    on conflict(booking_id) do nothing returning id into v_cancellation_id;
    if v_cancellation_id is not null then
      insert into public.booking_cancellation_events(booking_id,cancellation_id,actor_role,event_type,details)
        values(v_booking.id,v_cancellation_id,'system','checkout_expired',
          jsonb_build_object('checkout_expired_at',v_booking.checkout_expired_at,'previous_status','pending_payment'));
      perform public.create_cancellation_refund_case(v_cancellation_id,'renter');
      perform public.create_notification(v_booking.renter_id,'booking-checkout-expired:'||v_booking.id||':renter','bookings',
        'Checkout expired','The checkout reservation expired and the booking was cancelled.','/bookings/'||v_booking.id);
      if v_booking.owner_id<>v_booking.renter_id then
        perform public.create_notification(v_booking.owner_id,'booking-checkout-expired:'||v_booking.id||':owner','bookings',
          'Checkout expired','The checkout reservation expired and the booking was cancelled.','/bookings/'||v_booking.id);
      end if;
      v_count:=v_count+1;
    end if;
    v_cancellation_id:=null;
  end loop;
  return v_count;
end;
$$;
