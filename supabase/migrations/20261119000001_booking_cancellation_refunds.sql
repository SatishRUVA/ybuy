  if not public.operations_can_view_refunds() then raise exception 'Not authorized' using errcode='42501'; end if;
  with filtered as (
    select c.id cancellation_id,c.booking_id,c.initiator_id,c.initiator_role,c.cancellation_type,c.reason,
      c.previous_booking_status,c.created_at cancellation_created_at,
