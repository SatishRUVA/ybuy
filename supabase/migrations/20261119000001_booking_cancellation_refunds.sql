create table public.booking_cancellation_policies (
  id uuid primary key default gen_random_uuid(),
  version bigint generated by default as identity unique,
  effective_from timestamptz not null,
  effective_to timestamptz,
  renter_cutoff_hours numeric(8,2) not null check (renter_cutoff_hours >= 0),
  renter_rental_refund_percent numeric(5,2) not null check (renter_rental_refund_percent between 0 and 100),
  renter_refund_service_fee boolean not null default false,
  renter_refund_delivery_fee boolean not null default false,
  renter_refund_tax boolean not null default false,
  renter_refund_insurance boolean not null default false,
  renter_refund_deposit boolean not null default false,
  owner_cutoff_hours numeric(8,2) not null check (owner_cutoff_hours >= 0),
  owner_rental_refund_percent numeric(5,2) not null check (owner_rental_refund_percent between 0 and 100),
  owner_refund_service_fee boolean not null default false,
  owner_refund_delivery_fee boolean not null default false,
  owner_refund_tax boolean not null default false,
  owner_refund_insurance boolean not null default false,
  owner_refund_deposit boolean not null default false,
  automatic_processing boolean not null default false,
  created_by uuid not null references public.profiles(id),
  reason text not null check (length(reason) between 3 and 500),
  created_at timestamptz not null default clock_timestamp(),
  check (effective_to is null or effective_to > effective_from)
);

create table public.booking_cancellations (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null unique references public.bookings(id) on delete restrict,
  initiator_id uuid references public.profiles(id),
  initiator_role text not null check (initiator_role in ('renter','owner','system')),
  cancellation_type text not null check (cancellation_type in ('participant','checkout_expired')),
  reason text not null check (length(reason) between 3 and 500),
  previous_booking_status text not null,
  new_booking_status text not null default 'cancelled' check (new_booking_status = 'cancelled'),
  policy_id uuid references public.booking_cancellation_policies(id),
  policy_version bigint,
  original_payment_id uuid references public.payments(id),
  created_at timestamptz not null default clock_timestamp(),
  check ((initiator_role = 'system' and initiator_id is null and cancellation_type = 'checkout_expired')
    or (initiator_role <> 'system' and initiator_id is not null and cancellation_type = 'participant'))
);

create table public.cancellation_refund_cases (
  id uuid primary key default gen_random_uuid(),
  cancellation_id uuid not null unique references public.booking_cancellations(id) on delete restrict,
  booking_id uuid not null unique references public.bookings(id) on delete restrict,
  payment_id uuid references public.payments(id) on delete restrict,
  payment_intent_id text,
  currency text not null default 'usd',
  original_payment_amount numeric(10,2) not null default 0 check (original_payment_amount >= 0),
  eligible_amount numeric(10,2) not null default 0 check (eligible_amount >= 0),
  refund_amount numeric(10,2) not null default 0 check (refund_amount >= 0),
  status text not null check (status in (
    'not_applicable','pending_policy_review','pending_review','approved','processing',
    'partially_refunded','refunded','failed','rejected'
  )),
  automatic_processing boolean not null default false,
  policy_id uuid references public.booking_cancellation_policies(id),
  policy_version bigint,
  provider_refund_id text unique,
  provider_status text,
  provider_response jsonb,
  attempt integer not null default 0 check (attempt >= 0),
  approved_by uuid references public.profiles(id),
  approved_at timestamptz,
  rejected_by uuid references public.profiles(id),
  rejected_at timestamptz,
  decision_reason text,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp()
);

