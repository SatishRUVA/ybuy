create function public.confirm_booking_payment(
  p_booking_id uuid,p_checkout_session_id text,p_payment_intent_id text,p_amount numeric
) returns public.bookings language plpgsql security definer set search_path = '' as $$
declare
  b public.bookings;
  v_listing_id uuid;
  v_payment public.payments;
  v_exception public.checkout_payment_exceptions;
  v_cancellation public.booking_cancellations;
  v_refund_case public.cancellation_refund_cases;
  v_eligible numeric(10,2);
  v_refund_status text;
  v_role text;
begin
  select listing_id into v_listing_id from public.bookings where id=p_booking_id;
  if not found then raise exception 'Booking not found' using errcode='P0002'; end if;
  perform 1 from public.listings where id=v_listing_id for update;
  perform public.expire_listing_checkouts(v_listing_id);
  select * into b from public.bookings where id=p_booking_id for update;

  if b.status='cancelled' then
    select * into v_cancellation from public.booking_cancellations where booking_id=b.id for update;
    if found then
      if p_amount is null or p_amount::text in ('NaN','Infinity','-Infinity') or p_amount<>b.total or p_amount<=0
        or coalesce(p_checkout_session_id,'') not like 'cs_%'
        or coalesce(p_payment_intent_id,'') not like 'pi_%'
        or (b.checkout_session_id is not null and b.checkout_session_id<>p_checkout_session_id) then
        raise exception 'Payment details do not match the cancelled booking' using errcode='23514';
      end if;

      select * into v_payment from public.payments where stripe_checkout_session_id=p_checkout_session_id;
      if found then
        if v_payment.booking_id<>b.id or v_payment.stripe_payment_intent_id<>p_payment_intent_id
          or v_payment.amount<>p_amount or v_payment.status<>'succeeded' then
          raise exception 'Payment receipt conflicts with the cancelled booking' using errcode='23514';
        end if;
        return b;
      end if;

      select * into v_exception from public.checkout_payment_exceptions
        where checkout_session_id=p_checkout_session_id for update;
      if found then
        if v_exception.booking_id<>b.id or v_exception.payment_intent_id<>p_payment_intent_id
          or v_exception.amount<>p_amount then
          raise exception 'Payment receipt conflicts with a recorded checkout exception' using errcode='23514';
        end if;
      end if;
      if exists(select 1 from public.payments where booking_id=b.id and status='succeeded') then
        raise exception 'Booking already has a successful payment' using errcode='23514';
      end if;

      insert into public.payments(
        booking_id,stripe_checkout_session_id,stripe_payment_intent_id,amount,status
      ) values(b.id,p_checkout_session_id,p_payment_intent_id,p_amount,'succeeded');
      select * into v_payment from public.payments where stripe_checkout_session_id=p_checkout_session_id;
      if not found or v_payment.booking_id<>b.id or v_payment.stripe_payment_intent_id<>p_payment_intent_id
        or v_payment.amount<>p_amount then
        raise exception 'Payment receipt conflicts with an existing transaction' using errcode='23514';
      end if;

      select * into v_refund_case from public.cancellation_refund_cases
        where cancellation_id=v_cancellation.id for update;
      if not found then raise exception 'Cancelled booking has no refund case' using errcode='23514'; end if;
      v_role:=case when v_cancellation.initiator_role='owner' then 'owner' else 'renter' end;
      v_eligible:=public.booking_cancellation_late_payment_eligible_amount(
        b.id,v_cancellation.policy_id,v_role,v_cancellation.created_at,p_amount);
      v_refund_status:=case
        when v_cancellation.policy_id is null then 'pending_policy_review'
        when v_eligible>0 then 'pending_review'
        else 'not_applicable'
      end;
      if v_refund_case.status not in ('not_applicable','pending_policy_review','rejected') then
        raise exception 'Late payment conflicts with the current refund case state' using errcode='55000';
      end if;
      update public.cancellation_refund_cases set
        payment_id=v_payment.id,payment_intent_id=p_payment_intent_id,currency=v_payment.currency,
        original_payment_amount=p_amount,eligible_amount=v_eligible,refund_amount=0,status=v_refund_status,
        automatic_processing=false,
        rejected_by=null,rejected_at=null,
        decision_reason='Payment settled after cancellation; refund eligibility requires review.',
        updated_at=clock_timestamp()
        where id=v_refund_case.id;
      insert into public.booking_cancellation_events(
        booking_id,cancellation_id,refund_case_id,actor_role,event_type,details
      ) values(b.id,v_cancellation.id,v_refund_case.id,'system','late_payment_reconciled',
        jsonb_build_object('payment_id',v_payment.id,'payment_intent_id',p_payment_intent_id,
          'amount',p_amount,'previous_refund_status',v_refund_case.status,
          'eligible_amount',v_eligible,'refund_status',v_refund_status));
      perform public.create_notification(b.renter_id,
        'cancellation-late-payment:'||v_refund_case.id||':renter','payments',
        'Payment received after cancellation',
        case when v_refund_status='pending_policy_review'
          then 'A payment settled after cancellation. Refund eligibility is pending policy review; no amount is confirmed.'
          when v_refund_status='pending_review'
          then 'A payment settled after cancellation. Refund eligibility is pending review; no refund is confirmed.'
          else 'A payment settled after cancellation. The current policy does not provide an applicable refund.' end,
        '/bookings/'||b.id);
      if b.owner_id<>b.renter_id then
        perform public.create_notification(b.owner_id,
          'cancellation-late-payment:'||v_refund_case.id||':owner','payments',
          'Payment received after cancellation',
          'A payment settled after cancellation and is recorded in its separate refund case.','/bookings/'||b.id);
      end if;
      return b;
    end if;
  end if;

  return public.confirm_booking_payment_before_cancellation(
    p_booking_id,p_checkout_session_id,p_payment_intent_id,p_amount);
end;
$$;
