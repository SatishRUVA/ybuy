create function public.begin_cancellation_refund_processing(p_refund_case_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare r public.cancellation_refund_cases; b public.bookings; v_attempt integer;
begin
  perform public.operations_require_session();
  select * into r from public.cancellation_refund_cases where id=p_refund_case_id for update;
  if not found then raise exception 'Refund case not found' using errcode='P0002'; end if;
  select * into b from public.bookings where id=r.booking_id;
  if not (public.has_admin_permission('refunds.approve') or public.has_admin_permission('refunds.senior') or
    (r.automatic_processing and auth.uid() in (b.renter_id,b.owner_id))) then
    raise exception 'Not authorized to process this refund' using errcode='42501';
  end if;
  if r.status='approved' then
    if r.payment_id is null or r.payment_intent_id is null or r.refund_amount<=0 then
      raise exception 'A verified original payment is required' using errcode='23514';
    end if;
    update public.cancellation_refund_cases set status='processing',attempt=attempt+1,updated_at=clock_timestamp()
      where id=r.id returning attempt into v_attempt;
    insert into public.booking_cancellation_events(booking_id,cancellation_id,refund_case_id,actor_id,actor_role,event_type,details)
      values(r.booking_id,r.cancellation_id,r.id,auth.uid(),
        case when public.has_admin_permission('refunds.approve') or public.has_admin_permission('refunds.senior')
          then 'admin' else 'system' end,
        'refund_processing_started',jsonb_build_object('amount',r.refund_amount,'attempt',v_attempt));
    perform public.create_notification(b.renter_id,'cancellation-refund:'||r.id||':processing:'||v_attempt||':renter','payments',
      'Cancellation refund processing','Your approved refund has been sent for payment-provider processing. Final status is pending confirmation.',
      '/bookings/'||b.id);
    if b.owner_id<>b.renter_id then
      perform public.create_notification(b.owner_id,'cancellation-refund:'||r.id||':processing:'||v_attempt||':owner','payments',
        'Cancellation refund processing','An approved cancellation refund has been sent for payment-provider processing.',
        '/bookings/'||b.id);
    end if;
  elsif r.status='processing' then
    v_attempt:=r.attempt;
  else
    raise exception 'Only approved refunds can be processed' using errcode='55000';
  end if;
  return jsonb_build_object('case_id',r.id,'booking_id',r.booking_id,'payment_id',r.payment_id,
    'payment_intent_id',r.payment_intent_id,'amount',r.refund_amount,'currency',r.currency,'attempt',v_attempt);
end;
$$;
revoke all on function public.begin_cancellation_refund_processing(uuid) from public,anon;
grant execute on function public.begin_cancellation_refund_processing(uuid) to authenticated;

create function public.record_cancellation_refund_provider_result(
  p_refund_case_id uuid,p_provider_refund_id text,p_provider_status text,
  p_amount numeric,p_currency text,p_payment_intent_id text,p_attempt integer,p_provider_response jsonb
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare r public.cancellation_refund_cases; v_status text; b public.bookings; v_message text;
begin
  if auth.role()<>'service_role' then raise exception 'Service role required' using errcode='42501'; end if;
  select * into r from public.cancellation_refund_cases where id=p_refund_case_id for update;
  if not found then raise exception 'Refund case not found' using errcode='P0002'; end if;
  if r.status not in ('processing','failed','partially_refunded','refunded')
    or p_provider_refund_id is null or p_provider_refund_id !~ '^re_[A-Za-z0-9]+$'
    or p_amount is distinct from r.refund_amount or p_currency is distinct from r.currency
    or p_payment_intent_id is distinct from r.payment_intent_id or p_provider_status is null
    or p_attempt is distinct from r.attempt
    or p_provider_status not in ('succeeded','pending','failed','canceled') then
    raise exception 'Provider refund receipt does not match the approved case' using errcode='23514';
  end if;
  if r.provider_refund_id is not null and r.provider_refund_id<>p_provider_refund_id then
    raise exception 'A different provider refund is already attached to this case' using errcode='23514';
  end if;
  if r.status in ('partially_refunded','refunded')
    or (r.status='failed' and p_provider_status in ('pending','failed','canceled')) then
    return to_jsonb(r);
  end if;
  v_status:=case p_provider_status when 'succeeded' then
    case when p_amount>=r.original_payment_amount then 'refunded' else 'partially_refunded' end
    when 'pending' then 'processing' else 'failed' end;
  update public.cancellation_refund_cases set status=v_status,provider_refund_id=p_provider_refund_id,
    provider_status=p_provider_status,provider_response=coalesce(p_provider_response,'{}'::jsonb),
    updated_at=clock_timestamp() where id=r.id returning * into r;
  insert into public.booking_cancellation_events(booking_id,cancellation_id,refund_case_id,actor_role,event_type,details)
    values(r.booking_id,r.cancellation_id,r.id,'system','refund_provider_update',
      jsonb_build_object('provider_refund_id',p_provider_refund_id,'provider_status',p_provider_status,
        'status',v_status,'amount',p_amount,'currency',p_currency,'response',p_provider_response));
  select * into b from public.bookings where id=r.booking_id;
  v_message:=case v_status when 'refunded' then 'The payment provider confirmed your refund of USD '||r.refund_amount::text||'.'
    when 'partially_refunded' then 'The payment provider confirmed a partial refund of USD '||r.refund_amount::text||'.'
    when 'failed' then 'The payment provider could not complete the refund. Support will review the case.'
    else 'Your approved refund is being processed by the payment provider.' end;
  perform public.create_notification(b.renter_id,'cancellation-refund:'||r.id||':'||v_status||':renter','payments',
    case when v_status='failed' then 'Cancellation refund failed' else 'Cancellation refund update' end,v_message,'/bookings/'||b.id);
  if b.owner_id<>b.renter_id then
    perform public.create_notification(b.owner_id,'cancellation-refund:'||r.id||':'||v_status||':owner','payments',
      case when v_status='failed' then 'Cancellation refund failed' else 'Cancellation refund update' end,v_message,'/bookings/'||b.id);
  end if;
  return to_jsonb(r);
end;
$$;
revoke all on function public.record_cancellation_refund_provider_result(uuid,text,text,numeric,text,text,integer,jsonb) from public,anon,authenticated;
grant execute on function public.record_cancellation_refund_provider_result(uuid,text,text,numeric,text,text,integer,jsonb) to service_role;

create function public.record_cancellation_refund_provider_error(
  p_refund_case_id uuid,p_attempt integer,p_error_code text,p_provider_response jsonb
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare r public.cancellation_refund_cases; b public.bookings;
begin
  if auth.role()<>'service_role' then raise exception 'Service role required' using errcode='42501'; end if;
  select * into r from public.cancellation_refund_cases where id=p_refund_case_id for update;
  if not found then raise exception 'Refund case not found' using errcode='P0002'; end if;
  if r.status<>'processing' or r.attempt is distinct from p_attempt or r.provider_refund_id is not null
    or p_error_code is null or length(p_error_code)>100
    or p_provider_response is null or jsonb_typeof(p_provider_response)<>'object' then
    raise exception 'Provider failure does not match the active refund attempt' using errcode='23514';
  end if;
  update public.cancellation_refund_cases set status='failed',provider_status='failed',
    provider_response=p_provider_response,decision_reason='Payment provider rejected this refund attempt.',
    updated_at=clock_timestamp() where id=r.id returning * into r;
  insert into public.booking_cancellation_events(
    booking_id,cancellation_id,refund_case_id,actor_role,event_type,details
  ) values(r.booking_id,r.cancellation_id,r.id,'system','refund_provider_failure',
    jsonb_build_object('attempt',p_attempt,'error_code',p_error_code,'provider_response',p_provider_response));
  select * into b from public.bookings where id=r.booking_id;
  perform public.create_notification(b.renter_id,
    'cancellation-refund:'||r.id||':failed:renter','payments','Cancellation refund failed',
    'The payment provider could not complete the approved refund. Support can review and safely retry it.',
    '/bookings/'||b.id);
  if b.owner_id<>b.renter_id then
    perform public.create_notification(b.owner_id,
      'cancellation-refund:'||r.id||':failed:owner','payments','Cancellation refund failed',
      'The payment provider could not complete the approved cancellation refund.',
      '/bookings/'||b.id);
  end if;
  return to_jsonb(r);
end;
$$;
revoke all on function public.record_cancellation_refund_provider_error(uuid,integer,text,jsonb)
  from public,anon,authenticated;
grant execute on function public.record_cancellation_refund_provider_error(uuid,integer,text,jsonb) to service_role;

