create function public.admin_decide_cancellation_refund(
  p_refund_case_id uuid,p_action text,p_amount numeric,p_reason text,p_override boolean default false
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare r public.cancellation_refund_cases; v_reason text; v_status text;
begin
  if not (public.has_admin_permission('refunds.approve') or public.has_admin_permission('refunds.senior')) then
    raise exception 'Not authorized' using errcode='42501';
  end if;
  select * into r from public.cancellation_refund_cases where id=p_refund_case_id for update;
  if not found then raise exception 'Refund case not found' using errcode='P0002'; end if;
  if r.status not in ('pending_policy_review','pending_review','failed') then
    raise exception 'This refund case cannot be decided in its current state' using errcode='55000';
  end if;
  v_reason:=public.admin_clean_reason(p_reason);
  if p_action='reject' then
    update public.cancellation_refund_cases set status='rejected',rejected_by=auth.uid(),
      rejected_at=clock_timestamp(),decision_reason=v_reason,updated_at=clock_timestamp()
      where id=r.id returning * into r;
    v_status:='rejected';
  elsif p_action='approve' then
    if p_amount is null or p_amount<=0 or p_amount<>round(p_amount,2)
      or p_amount>r.original_payment_amount then
      raise exception 'Refund amount must be positive and cannot exceed the original payment' using errcode='22023';
    end if;
    if (p_override or r.policy_version is null or p_amount>r.eligible_amount)
      and not public.has_admin_permission('refunds.senior') then
      raise exception 'Senior refund permission is required for a policy override' using errcode='42501';
    end if;
    if p_amount>r.original_payment_amount-(select coalesce(sum(x.refund_amount),0)
      from public.cancellation_refund_cases x where x.payment_id=r.payment_id and x.status in ('processing','partially_refunded','refunded')) then
      raise exception 'Refund amount exceeds the remaining payment balance' using errcode='23514';
    end if;
    update public.cancellation_refund_cases set status='approved',refund_amount=p_amount,
      approved_by=auth.uid(),approved_at=clock_timestamp(),decision_reason=v_reason,
      provider_refund_id=case when r.status='failed' then null else provider_refund_id end,
      provider_status=case when r.status='failed' then null else provider_status end,
      provider_response=case when r.status='failed' then null else provider_response end,
      updated_at=clock_timestamp()
      where id=r.id returning * into r;
    v_status:='approved';
  else
    raise exception 'Action must be approve or reject' using errcode='22023';
  end if;
  insert into public.booking_cancellation_events(booking_id,cancellation_id,refund_case_id,actor_id,actor_role,event_type,details)
    values(r.booking_id,r.cancellation_id,r.id,auth.uid(),'admin','refund_'||v_status,
      jsonb_build_object('reason',v_reason,'amount',r.refund_amount,'override',coalesce(p_override,false)));
  perform public.admin_write_audit('cancellation_refund.'||v_status,'cancellation_refund_case',r.id::text,
    null,to_jsonb(r),v_reason);
  perform public.create_notification((select renter_id from public.bookings where id=r.booking_id),
    'cancellation-refund:'||r.id||':'||v_status,'payments',
    case when v_status='approved' then 'Cancellation refund approved' else 'Cancellation refund rejected' end,
    case when v_status='approved' then 'A refund of USD '||r.refund_amount::text||' is approved and will be processed.'
      else 'The cancellation refund request was rejected. Contact support for details.' end,
    '/bookings/'||r.booking_id);
  perform public.create_notification((select owner_id from public.bookings where id=r.booking_id),
    'cancellation-refund:'||r.id||':'||v_status||':owner','payments',
    case when v_status='approved' then 'Cancellation refund approved' else 'Cancellation refund rejected' end,
    case when v_status='approved' then 'A refund of USD '||r.refund_amount::text||' is approved and will be processed.'
      else 'The cancellation refund request was rejected. Contact support for details.' end,
    '/bookings/'||r.booking_id);
  return to_jsonb(r);
end;
$$;
