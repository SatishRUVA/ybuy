create function public.booking_cancellation_pickup_at(p_booking_id uuid)
returns timestamptz language sql stable security definer set search_path = '' as $$
  select coalesce(
    (select s.starts_at from public.booking_pickup_slots s
      where s.booking_id = b.id and s.kind = 'pickup' and s.status = 'approved'),
    ((b.start_date::text || ' 00:00:00')::timestamp at time zone coalesce(
      (select l.time_zone from public.listing_pickup_locations l where l.listing_id = b.listing_id), 'UTC'))
  )
  from public.bookings b where b.id = p_booking_id
$$;
