create function public.booking_cancellation_quote_data(
  p_booking_id uuid,p_actor_role text,p_policy_at timestamptz default now()
)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  b public.bookings;
  p public.booking_cancellation_policies;
  v_payment public.payments;
  v_payment_count integer;
  v_pickup_at timestamptz;
  v_percent numeric;
  v_cutoff numeric;
  v_fee boolean;
  v_delivery_fee boolean;
  v_tax boolean;
  v_insurance boolean;
  v_deposit boolean;
  v_eligible numeric(10,2) := 0;
  v_refund_status text := 'not_applicable';
  v_allowed boolean;
  v_reason text;
begin
  select * into b from public.bookings where id = p_booking_id;
  if not found then raise exception 'Booking not found' using errcode = 'P0002'; end if;
  if p_actor_role not in ('renter','owner') then raise exception 'Invalid cancellation role' using errcode = '22023'; end if;

  v_allowed := b.status in ('requested','pending_payment','confirmed')
    and not exists(select 1 from public.booking_handoffs h where h.booking_id=b.id and h.actual_pickup_at is not null);
  v_reason := case
    when b.status = 'cancelled' then 'This booking has already been cancelled.'
    when b.status = 'completed' then 'Completed bookings cannot be cancelled.'
    when b.status not in ('requested','pending_payment','confirmed') then 'This booking is no longer eligible for cancellation.'
    when exists(select 1 from public.booking_handoffs h where h.booking_id=b.id and h.actual_pickup_at is not null)
      then 'A booking cannot be cancelled after pickup.'
    else null end;

  select * into p from public.booking_cancellation_policies
    where effective_from <= p_policy_at and (effective_to is null or effective_to > p_policy_at)
    order by effective_from desc, version desc limit 1;
  v_pickup_at := public.booking_cancellation_pickup_at(p_booking_id);
  select count(*) into v_payment_count from public.payments where booking_id=b.id and status='succeeded';
  if v_payment_count = 1 then
    select * into v_payment from public.payments where booking_id=b.id and status='succeeded';
  end if;

  if v_payment_count > 1 then
    v_refund_status := 'pending_review';
  elsif v_payment_count = 1 and
    (v_payment.amount <> b.total or v_payment.currency <> 'usd' or v_payment.stripe_payment_intent_id is null) then
    v_refund_status := 'pending_review';
  elsif v_payment_count = 1 and p.id is null then
    v_refund_status := 'pending_policy_review';
  elsif v_payment_count = 1 then
    if p_actor_role = 'renter' then
      v_cutoff:=p.renter_cutoff_hours; v_percent:=p.renter_rental_refund_percent;
      v_fee:=p.renter_refund_service_fee; v_delivery_fee:=p.renter_refund_delivery_fee;
      v_tax:=p.renter_refund_tax;
      v_insurance:=p.renter_refund_insurance; v_deposit:=p.renter_refund_deposit;
    else
      v_cutoff:=p.owner_cutoff_hours; v_percent:=p.owner_rental_refund_percent;
      v_fee:=p.owner_refund_service_fee; v_delivery_fee:=p.owner_refund_delivery_fee;
      v_tax:=p.owner_refund_tax;
      v_insurance:=p.owner_refund_insurance; v_deposit:=p.owner_refund_deposit;
    end if;
    if v_pickup_at - now() >= v_cutoff * interval '1 hour' then
      v_eligible:=round(b.subtotal * v_percent / 100,2)
        + case when v_fee then b.service_fee_amount else 0 end
        + case when v_delivery_fee then coalesce(b.delivery_fee_amount,0) else 0 end
        + case when v_tax then b.tax_amount else 0 end
        + case when v_insurance then b.insurance_amount else 0 end
        + case when v_deposit and b.deposit_collection_model='captured' then b.deposit else 0 end;
      v_eligible:=least(v_eligible,v_payment.amount);
    end if;
    v_refund_status:=case when v_eligible>0 and p.automatic_processing then 'approved'
      when v_eligible>0 then 'pending_review' else 'not_applicable' end;
  end if;
  return jsonb_build_object(
    'booking_id',b.id,'booking_status',b.status,'allowed',v_allowed,'ineligible_reason',v_reason,
    'pickup_at',v_pickup_at,'refund_status',v_refund_status,'refund_amount',v_eligible,
    'currency',coalesce(v_payment.currency,'usd'),'policy_version',p.version,
    'automatic_processing',coalesce(p.automatic_processing,false)
  );
end;
$$;
revoke all on function public.booking_cancellation_quote_data(uuid,text,timestamptz) from public, anon, authenticated;

create function public.get_booking_cancellation_quote(p_booking_id uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare b public.bookings;
begin
  perform public.operations_require_session();
  select * into b from public.bookings where id=p_booking_id and auth.uid() in (renter_id,owner_id);
  if not found then raise exception 'Booking not found or not a participant' using errcode='42501'; end if;
  return public.booking_cancellation_quote_data(p_booking_id,
    case when b.renter_id=auth.uid() then 'renter' else 'owner' end);
end;
$$;
revoke all on function public.get_booking_cancellation_quote(uuid) from public, anon;
grant execute on function public.get_booking_cancellation_quote(uuid) to authenticated;

create function public.booking_cancellation_late_payment_eligible_amount(
  p_booking_id uuid,p_policy_id uuid,p_actor_role text,p_cancelled_at timestamptz,p_payment_amount numeric
) returns numeric language plpgsql stable security definer set search_path = '' as $$
declare
  b public.bookings;
  p public.booking_cancellation_policies;
  v_role text:=case when p_actor_role='owner' then 'owner' else 'renter' end;
  v_cutoff numeric;
  v_percent numeric;
  v_eligible numeric(10,2):=0;
begin
  if p_policy_id is null or p_cancelled_at is null or p_payment_amount is null or p_payment_amount<=0 then
    return 0;
  end if;
  select * into b from public.bookings where id=p_booking_id;
  select * into p from public.booking_cancellation_policies where id=p_policy_id;
  if not found then return 0; end if;
  if v_role='owner' then
    v_cutoff:=p.owner_cutoff_hours;
    v_percent:=p.owner_rental_refund_percent;
    v_eligible:=case when p.owner_refund_service_fee then b.service_fee_amount else 0 end
      +case when p.owner_refund_delivery_fee then coalesce(b.delivery_fee_amount,0) else 0 end
      +case when p.owner_refund_tax then b.tax_amount else 0 end
      +case when p.owner_refund_insurance then b.insurance_amount else 0 end
      +case when p.owner_refund_deposit and b.deposit_collection_model='captured' then b.deposit else 0 end;
  else
    v_cutoff:=p.renter_cutoff_hours;
    v_percent:=p.renter_rental_refund_percent;
    v_eligible:=case when p.renter_refund_service_fee then b.service_fee_amount else 0 end
      +case when p.renter_refund_delivery_fee then coalesce(b.delivery_fee_amount,0) else 0 end
      +case when p.renter_refund_tax then b.tax_amount else 0 end
      +case when p.renter_refund_insurance then b.insurance_amount else 0 end
      +case when p.renter_refund_deposit and b.deposit_collection_model='captured' then b.deposit else 0 end;
  end if;
  if public.booking_cancellation_pickup_at(p_booking_id)-p_cancelled_at < v_cutoff*interval '1 hour' then
    return 0;
  end if;
  return least(round(b.subtotal*v_percent/100,2)+v_eligible,p_payment_amount);
end;
$$;
revoke all on function public.booking_cancellation_late_payment_eligible_amount(uuid,uuid,text,timestamptz,numeric)
  from public,anon,authenticated;

create function public.create_cancellation_refund_case(p_cancellation_id uuid,p_role text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  c public.booking_cancellations;
  b public.bookings;
  p public.booking_cancellation_policies;
  payment_row public.payments;
  payment_count integer;
  q jsonb;
  v_case_id uuid;
  v_status text;
  v_amount numeric(10,2);
  v_policy_at timestamptz;
begin
  select * into c from public.booking_cancellations where id=p_cancellation_id;
  select * into b from public.bookings where id=c.booking_id;
  v_policy_at:=case when c.cancellation_type='checkout_expired' then b.checkout_expired_at else c.created_at end;
  if c.policy_id is not null then
    select * into p from public.booking_cancellation_policies where id=c.policy_id;
  else
    select * into p from public.booking_cancellation_policies
      where effective_from<=v_policy_at and (effective_to is null or effective_to>v_policy_at)
      order by effective_from desc,version desc limit 1;
  end if;
  select count(*) into payment_count from public.payments where booking_id=b.id and status='succeeded';
  if payment_count=1 then select * into payment_row from public.payments where booking_id=b.id and status='succeeded'; end if;
  q:=public.booking_cancellation_quote_data(b.id,p_role,v_policy_at);
  v_status:=q->>'refund_status'; v_amount:=coalesce((q->>'refund_amount')::numeric,0);
  insert into public.cancellation_refund_cases(
    cancellation_id,booking_id,payment_id,payment_intent_id,currency,original_payment_amount,
    eligible_amount,refund_amount,status,automatic_processing,policy_id,policy_version
  ) values (
    c.id,b.id,payment_row.id,payment_row.stripe_payment_intent_id,coalesce(payment_row.currency,'usd'),
    coalesce(payment_row.amount,0),v_amount,
    case when v_status='approved' then v_amount else 0 end,v_status,
    coalesce(p.automatic_processing,false),p.id,p.version
  ) returning id into v_case_id;
  if payment_count>1 then
    update public.cancellation_refund_cases set decision_reason='Multiple successful payments require manual reconciliation.'
      where id=v_case_id;
  end if;
  insert into public.booking_cancellation_events(booking_id,cancellation_id,refund_case_id,actor_id,actor_role,event_type,details)
    values(b.id,c.id,v_case_id,c.initiator_id,c.initiator_role,'refund_case_created',
      jsonb_build_object('status',v_status,'eligible_amount',v_amount,'payment_id',payment_row.id,'policy_version',p.version));
  perform public.create_notification(b.renter_id,'cancellation-refund:'||v_case_id||':created:renter','payments',
    'Cancellation refund status',case when v_status='pending_policy_review'
      then 'Your cancellation is recorded. Refund eligibility is pending policy review; no refund amount is confirmed.'
      when v_status='pending_review' then 'Your cancellation is recorded. Any applicable refund is pending review.'
      when v_status='approved' then 'Your cancellation is recorded. The eligible refund is approved and will be processed.'
      else 'Your cancellation is recorded. No payment refund applies under the current payment and policy.' end,
    '/bookings/'||b.id);
  if b.owner_id<>b.renter_id then
      perform public.create_notification(b.owner_id,'cancellation-refund:'||v_case_id||':created:owner','payments',
        'Cancellation refund status','A cancellation refund case was created. Its status is tracked separately from the booking.',
        '/bookings/'||b.id);
  end if;
  return v_case_id;
end;
$$;
revoke all on function public.create_cancellation_refund_case(uuid,text) from public, anon, authenticated;

do $$
declare
  b public.bookings;
  p public.booking_cancellation_policies;
  v_cancellation_id uuid;
begin
  for b in select * from public.bookings
    where status='cancelled' and checkout_expired_at is not null
      and not exists(select 1 from public.booking_cancellations c where c.booking_id=bookings.id)
  loop
    select * into p from public.booking_cancellation_policies
      where effective_from<=b.checkout_expired_at
        and (effective_to is null or effective_to>b.checkout_expired_at)
      order by effective_from desc,version desc limit 1;
    insert into public.booking_cancellations(
      booking_id,initiator_role,cancellation_type,reason,previous_booking_status,policy_id,policy_version
    ) values(b.id,'system','checkout_expired','Checkout reservation expired.','pending_payment',p.id,p.version)
    on conflict(booking_id) do nothing returning id into v_cancellation_id;
    if v_cancellation_id is not null then
      insert into public.booking_cancellation_events(
        booking_id,cancellation_id,actor_role,event_type,details
      ) values(b.id,v_cancellation_id,'system','checkout_expired',
        jsonb_build_object('checkout_expired_at',b.checkout_expired_at,'previous_status','pending_payment'));
      perform public.create_cancellation_refund_case(v_cancellation_id,'renter');
      perform public.create_notification(b.renter_id,
        'booking-checkout-expired:'||b.id||':renter','bookings',
        'Checkout expired','The checkout reservation expired and the booking was cancelled.','/bookings/'||b.id);
      if b.owner_id<>b.renter_id then
        perform public.create_notification(b.owner_id,
          'booking-checkout-expired:'||b.id||':owner','bookings',
          'Checkout expired','The checkout reservation expired and the booking was cancelled.','/bookings/'||b.id);
      end if;
    end if;
    v_cancellation_id:=null;
  end loop;
end;
$$;

create or replace function public.cancel_booking(p_booking_id uuid,p_reason text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  b public.bookings;
  h public.booking_handoffs;
  v_role text;
  v_quote jsonb;
  v_cancellation_id uuid;
  v_refund_case_id uuid;
begin
  perform public.operations_require_session();
  select * into b from public.bookings where id=p_booking_id for update;
  if not found then raise exception 'Booking not found' using errcode='P0002'; end if;
  if b.renter_id<>auth.uid() and b.owner_id<>auth.uid() then
    raise exception 'Not a participant in this booking' using errcode='42501';
  end if;
  if p_reason is null or length(btrim(p_reason)) not between 3 and 500
    or p_reason ~* '<\s*/?\s*[a-zA-Z!?]|javascript\s*:|[\x01-\x08\x0b\x0c\x0e-\x1f]' then
    raise exception 'Enter a cancellation reason between 3 and 500 characters' using errcode='22023';
  end if;
  v_role:=case when b.renter_id=auth.uid() then 'renter' else 'owner' end;
  v_quote:=public.booking_cancellation_quote_data(p_booking_id,v_role);
  if not (v_quote->>'allowed')::boolean then
    raise exception '%',coalesce(v_quote->>'ineligible_reason','Booking can no longer be cancelled') using errcode='55000';
  end if;
  select * into h from public.booking_handoffs where booking_id=p_booking_id for update;
  if h.actual_pickup_at is not null then
    raise exception 'A picked-up rental cannot be cancelled' using errcode='55000';
  end if;
  insert into public.booking_cancellations(
    booking_id,initiator_id,initiator_role,cancellation_type,reason,previous_booking_status,
    policy_id,policy_version,original_payment_id
  ) values (
    b.id,auth.uid(),v_role,'participant',btrim(p_reason),b.status,
    (select id from public.booking_cancellation_policies where version=(v_quote->>'policy_version')::bigint),
    (v_quote->>'policy_version')::bigint,
    (select id from public.payments where booking_id=b.id and status='succeeded' order by created_at desc limit 1)
  ) returning id into v_cancellation_id;
  if h.booking_id is not null then
    update public.booking_handoffs set status='cancelled' where booking_id=p_booking_id;
    update public.booking_handoff_otp_challenges set invalidated_at=clock_timestamp(),otp_ciphertext=''::bytea
      where booking_id=p_booking_id and used_at is null;
    perform public.record_booking_handoff_event(p_booking_id,'booking_cancelled_before_pickup');
  end if;
  update public.bookings set status='cancelled' where id=p_booking_id returning * into b;
  v_refund_case_id:=public.create_cancellation_refund_case(v_cancellation_id,v_role);
  insert into public.booking_cancellation_events(booking_id,cancellation_id,refund_case_id,actor_id,actor_role,event_type,details)
    values(b.id,v_cancellation_id,v_refund_case_id,auth.uid(),v_role,'booking_cancelled',
      jsonb_build_object('reason',btrim(p_reason),'previous_status',v_quote->>'booking_status','new_status',b.status));
  perform public.create_notification(b.renter_id,'booking-cancelled:'||b.id||':'||v_cancellation_id||':renter','bookings',
    'Booking cancelled','The booking was cancelled by the '||v_role||'. Reason: '||btrim(p_reason),'/bookings/'||b.id);
  if b.owner_id<>b.renter_id then
    perform public.create_notification(b.owner_id,'booking-cancelled:'||b.id||':'||v_cancellation_id||':owner','bookings',
      'Booking cancelled','The booking was cancelled by the '||v_role||'. Reason: '||btrim(p_reason),'/bookings/'||b.id);
  end if;
  return jsonb_build_object('booking',to_jsonb(b),'cancellation_id',v_cancellation_id,
    'refund_case_id',v_refund_case_id,'refund_status',v_quote->>'refund_status',
    'refund_amount',v_quote->>'refund_amount');
end;
$$;
