create function public.enforce_booking_checkout_expiry()
returns trigger language plpgsql set search_path = '' as $$
declare v_deadline timestamptz:=clock_timestamp()+interval '15 minutes';
begin
  if new.status<>'pending_payment' then return new; end if;
  if tg_op='INSERT' or old.status<>'pending_payment' then
    new.checkout_expires_at:=least(coalesce(new.checkout_expires_at,v_deadline),v_deadline);
    new.checkout_expired_at:=null;
  else
    new.checkout_expires_at:=least(
      coalesce(new.checkout_expires_at,old.checkout_expires_at,v_deadline),
      coalesce(old.checkout_expires_at,v_deadline)
    );
  end if;
  return new;
end;
$$;
